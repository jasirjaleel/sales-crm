-- ==========================================
-- SALES PIPELINE
-- leads.status now holds the stage:
--   new, contacted, interested, meeting_booked, proposal_sent, won, lost
-- leads.last_outcome holds the latest call result.
-- Stage names and order are mirrored in src/utils/pipeline.js.
-- ==========================================
ALTER TABLE public.leads
  ADD COLUMN IF NOT EXISTS last_outcome TEXT,
  ADD COLUMN IF NOT EXISTS deal_value NUMERIC(12,2),
  ADD COLUMN IF NOT EXISTS expected_close_date DATE,
  ADD COLUMN IF NOT EXISTS stage_changed_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP;

-- Map old statuses before any trigger exists, so this is not recorded as agents moving leads.
UPDATE public.leads SET last_outcome = status
  WHERE status IN ('no_answer', 'call_back', 'send_info', 'not_interested');
UPDATE public.leads SET status = 'won' WHERE status = 'closed';
UPDATE public.leads SET status = 'lost', lost_reason = COALESCE(lost_reason, 'Not Interested')
  WHERE status = 'not_interested';
UPDATE public.leads SET status = 'contacted'
  WHERE status NOT IN ('new', 'contacted', 'interested', 'meeting_booked', 'proposal_sent', 'won', 'lost');
UPDATE public.leads SET stage_changed_at = COALESCE(last_called_at, created_at, CURRENT_TIMESTAMP);

-- ------------------------------------------
-- Stage history
-- ------------------------------------------
CREATE TABLE IF NOT EXISTS public.lead_stage_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id BIGINT NOT NULL REFERENCES public.leads(id) ON DELETE CASCADE,
  from_stage TEXT,
  to_stage TEXT NOT NULL,
  changed_by UUID REFERENCES public.profiles(id),
  changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_stage_events_lead ON public.lead_stage_events(lead_id, changed_at);
CREATE INDEX IF NOT EXISTS idx_stage_events_changed_at ON public.lead_stage_events(changed_at);

ALTER TABLE public.lead_stage_events ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Read stage history on accessible leads" ON public.lead_stage_events;
CREATE POLICY "Read stage history on accessible leads" ON public.lead_stage_events FOR SELECT TO authenticated
  USING (public.can_access_lead(lead_id));
-- No write policies: rows only come from the trigger below.

CREATE OR REPLACE FUNCTION public.stage_rank(p_stage TEXT)
RETURNS INTEGER
LANGUAGE sql IMMUTABLE SET search_path = ''
AS $$
  SELECT CASE p_stage
    WHEN 'new' THEN 0 WHEN 'contacted' THEN 1 WHEN 'interested' THEN 2
    WHEN 'meeting_booked' THEN 3 WHEN 'proposal_sent' THEN 4 WHEN 'won' THEN 5
    ELSE -1 END;
$$;

CREATE OR REPLACE FUNCTION public.leads_before_stage_change()
RETURNS TRIGGER
LANGUAGE plpgsql SET search_path = ''
AS $$
BEGIN
  NEW.updated_at := CURRENT_TIMESTAMP;
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    NEW.stage_changed_at := CURRENT_TIMESTAMP;
    IF NEW.status <> 'lost' THEN
      NEW.lost_reason := NULL;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.leads_after_stage_change()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
BEGIN
  INSERT INTO public.lead_stage_events (lead_id, from_stage, to_stage, changed_by)
  VALUES (NEW.id, OLD.status, NEW.status, auth.uid());
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS leads_before_stage_change ON public.leads;
DROP TRIGGER IF EXISTS leads_after_stage_change ON public.leads;
CREATE TRIGGER leads_before_stage_change BEFORE UPDATE ON public.leads
  FOR EACH ROW EXECUTE FUNCTION public.leads_before_stage_change();
CREATE TRIGGER leads_after_stage_change AFTER UPDATE OF status ON public.leads
  FOR EACH ROW WHEN (OLD.status IS DISTINCT FROM NEW.status)
  EXECUTE FUNCTION public.leads_after_stage_change();

-- ------------------------------------------
-- Finance moves the pipeline
-- ------------------------------------------
-- A quotation marked Sent moves an open lead up to Proposal Sent, never backwards.
CREATE OR REPLACE FUNCTION public.quotation_moves_stage()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
BEGIN
  IF NEW.status = 'Sent' AND (TG_OP = 'INSERT' OR OLD.status IS DISTINCT FROM NEW.status) THEN
    UPDATE public.leads
    SET status = CASE WHEN public.stage_rank(status) BETWEEN 0 AND 3 THEN 'proposal_sent' ELSE status END,
        deal_value = COALESCE(deal_value, NEW.price - COALESCE(NEW.discount, 0))
    WHERE id = NEW.lead_id;
  END IF;
  RETURN NULL;
END;
$$;

-- An invoice marked Paid means the deal is won, whatever stage the lead was in.
CREATE OR REPLACE FUNCTION public.invoice_moves_stage()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
BEGIN
  IF NEW.status = 'Paid' AND (TG_OP = 'INSERT' OR OLD.status IS DISTINCT FROM NEW.status) THEN
    UPDATE public.leads
    SET status = 'won',
        deal_value = COALESCE(deal_value, NEW.amount - COALESCE(NEW.discount, 0))
    WHERE id = NEW.lead_id;
  END IF;
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS quotation_moves_stage ON public.quotations;
DROP TRIGGER IF EXISTS invoice_moves_stage ON public.invoices;
CREATE TRIGGER quotation_moves_stage AFTER INSERT OR UPDATE OF status ON public.quotations
  FOR EACH ROW EXECUTE FUNCTION public.quotation_moves_stage();
CREATE TRIGGER invoice_moves_stage AFTER INSERT OR UPDATE OF status ON public.invoices
  FOR EACH ROW EXECUTE FUNCTION public.invoice_moves_stage();
