-- ==========================================
-- CRM SCHEMA (V4.0)
-- ==========================================

-- 1. PROFILES TABLE (Linked to Supabase Auth)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID REFERENCES auth.users NOT NULL PRIMARY KEY,
  name TEXT,
  email TEXT UNIQUE NOT NULL,
  role TEXT DEFAULT 'agent',
  daily_target INTEGER DEFAULT 30,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 2. LEAD LISTS TABLE
CREATE TABLE IF NOT EXISTS public.lead_lists (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT,
  total_leads INTEGER DEFAULT 0,
  uploaded_by UUID REFERENCES public.profiles(id),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 3. LEADS TABLE
CREATE TABLE IF NOT EXISTS public.leads (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  list_id BIGINT REFERENCES public.lead_lists(id) ON DELETE CASCADE,
  assigned_to UUID REFERENCES public.profiles(id),
  name TEXT NOT NULL,
  phone TEXT,
  website TEXT,
  location TEXT,
  google_maps_url TEXT,
  business_type TEXT,
  category TEXT,
  reviews INTEGER DEFAULT 0,
  average_rating DECIMAL(3,2) DEFAULT 0,
  ai_score DECIMAL(4,1) DEFAULT 0,
  incomplete INTEGER DEFAULT 0,
  phone_valid INTEGER DEFAULT 1,
  status TEXT DEFAULT 'new',
  notes TEXT,
  last_called_at TIMESTAMP WITH TIME ZONE,
  assigned_date TIMESTAMP WITH TIME ZONE,
  queue_date TEXT,
  last_activity TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Indexing for performance
CREATE INDEX IF NOT EXISTS idx_leads_status ON public.leads(status);
CREATE INDEX IF NOT EXISTS idx_leads_category ON public.leads(category);
CREATE INDEX IF NOT EXISTS idx_leads_assigned ON public.leads(assigned_to);

-- 4. CALL LOGS TABLE
CREATE TABLE IF NOT EXISTS public.call_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id BIGINT REFERENCES public.leads(id) ON DELETE CASCADE,
  agent_id UUID REFERENCES public.profiles(id),
  outcome TEXT NOT NULL,
  notes TEXT,
  called_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 5. FOLLOW UPS TABLE
CREATE TABLE IF NOT EXISTS public.follow_ups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id BIGINT REFERENCES public.leads(id) ON DELETE CASCADE,
  agent_id UUID REFERENCES public.profiles(id),
  scheduled_at TIMESTAMP WITH TIME ZONE NOT NULL,
  notes TEXT,
  completed INTEGER DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 6. WHATSAPP TEMPLATES TABLE
CREATE TABLE IF NOT EXISTS public.whatsapp_templates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  message TEXT NOT NULL,
  created_by UUID REFERENCES public.profiles(id),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- ==========================================
-- TRIGGERS & FUNCTIONS
-- ==========================================

-- Trigger function to automatically create a profile for new users
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, email, name, role)
  VALUES (new.id, new.email, new.raw_user_meta_data->>'name', 'agent');
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger to run the function when a user signs up in Supabase Auth
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- ==========================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- ==========================================

-- Enable RLS on all tables
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lead_lists ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.leads ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.call_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.follow_ups ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.whatsapp_templates ENABLE ROW LEVEL SECURITY;

-- 1. PROFILES: Anyone authenticated can read profiles (for assignment dropdowns)
CREATE POLICY "Profiles are viewable by everyone" ON public.profiles FOR SELECT USING (auth.role() = 'authenticated');
-- Only users themselves or admins can update their profiles
CREATE POLICY "Users can update own profile" ON public.profiles FOR UPDATE USING (auth.uid() = id);

-- 2. LEADS: Viewable by assigned agent or if unassigned. Admins can see all.
-- Note: A simplified version for now where authenticated users can view all leads to prevent breaking Team Views.
CREATE POLICY "Leads are viewable by authenticated users" ON public.leads FOR SELECT USING (auth.role() = 'authenticated');
CREATE POLICY "Leads can be updated by authenticated users" ON public.leads FOR UPDATE USING (auth.role() = 'authenticated');
CREATE POLICY "Leads can be inserted by authenticated users" ON public.leads FOR INSERT WITH CHECK (auth.role() = 'authenticated');

-- Same baseline permissive auth for CRM functionality initially (can be tightened later)
CREATE POLICY "Lead lists full access" ON public.lead_lists FOR ALL USING (auth.role() = 'authenticated');
CREATE POLICY "Call logs full access" ON public.call_logs FOR ALL USING (auth.role() = 'authenticated');
CREATE POLICY "Follow ups full access" ON public.follow_ups FOR ALL USING (auth.role() = 'authenticated');
CREATE POLICY "WhatsApp templates full access" ON public.whatsapp_templates FOR ALL USING (auth.role() = 'authenticated');

