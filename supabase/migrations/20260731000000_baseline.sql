-- FINANCE MIGRATION
-- Adds Quotations and Invoices tables
-- ==========================================

-- 1. QUOTATIONS TABLE
CREATE TABLE IF NOT EXISTS public.quotations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id BIGINT REFERENCES public.leads(id) ON DELETE CASCADE,
  service TEXT NOT NULL,
  price DECIMAL(10,2) NOT NULL,
  discount DECIMAL(10,2) DEFAULT 0,
  timeline TEXT,
  deliverables TEXT,
  terms TEXT,
  status TEXT DEFAULT 'Draft', -- Draft, Sent, Accepted, Rejected, Invoiced
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  created_by UUID REFERENCES public.profiles(id)
);

-- 2. INVOICES TABLE
CREATE TABLE IF NOT EXISTS public.invoices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quotation_id BIGINT REFERENCES public.quotations(id) ON DELETE SET NULL,
  lead_id BIGINT REFERENCES public.leads(id) ON DELETE CASCADE,
  amount DECIMAL(10,2) NOT NULL,
  discount DECIMAL(10,2) DEFAULT 0,
  issue_date DATE,
  due_date DATE,
  notes TEXT,
  status TEXT DEFAULT 'Unpaid', -- Unpaid, Partially Paid, Paid, Overdue
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  created_by UUID REFERENCES public.profiles(id)
);

-- Indexing for performance
CREATE INDEX IF NOT EXISTS idx_quotations_lead ON public.quotations(lead_id);
CREATE INDEX IF NOT EXISTS idx_invoices_lead ON public.invoices(lead_id);

-- Enable RLS
ALTER TABLE public.quotations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.invoices ENABLE ROW LEVEL SECURITY;

-- Allow full access for authenticated users (as per current schema baseline)
CREATE POLICY "Quotations full access" ON public.quotations FOR ALL USING (auth.role() = 'authenticated');
CREATE POLICY "Invoices full access" ON public.invoices FOR ALL USING (auth.role() = 'authenticated');
